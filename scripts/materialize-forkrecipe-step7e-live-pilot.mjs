import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import {
  FORKRECIPE_STEP7E_EXPECTED_COMMIT,
  FORKRECIPE_STEP7E_EXPECTED_RECIPE_COUNT,
  buildForkRecipeStep7ePilot
} from "./forkrecipe-step7e-core.mjs";
import { ALL_RECIPES } from "../src/data/corpus-v1.js";

export const STEP7E_LIVE_RECIPE_COUNT = 500;
export const STEP7E_LIVE_CHUNK_SIZE = 10;
export const STEP7E_LIVE_CHUNK_COUNT = STEP7E_LIVE_RECIPE_COUNT / STEP7E_LIVE_CHUNK_SIZE;

const sha256 = value => createHash("sha256").update(value).digest("hex");
const encoder = new TextEncoder();

function parseArgs(argv) {
  const options = { source: null, output: ".tmp/step7e-live-generated" };
  for (const arg of argv) {
    if (arg.startsWith("--source=")) options.source = arg.slice("--source=".length);
    else if (arg.startsWith("--out=")) options.output = arg.slice("--out=".length) || options.output;
  }
  if (!options.source) throw new Error("--source=<checked-out forkrecipe-recipes path> is required");
  return options;
}

async function loadSourceEntries(sourceRoot) {
  const recipesDir = resolve(sourceRoot, "recipes");
  const files = (await readdir(recipesDir))
    .filter(file => file.endsWith(".js") && file !== "_template.js" && file !== "index.js")
    .sort();
  const entries = [];
  for (const fileName of files) {
    const mod = await import(pathToFileURL(resolve(recipesDir, fileName)).href);
    entries.push({ fileName, recipe: mod.default });
  }
  return entries;
}

export function deterministicStep7eSelection(items, count = STEP7E_LIVE_RECIPE_COUNT) {
  if (!Array.isArray(items) || items.length < count) throw new Error("STEP7E_SELECTION_SOURCE_TOO_SMALL");
  return Array.from({ length: count }, (_, index) => items[Math.floor(index * items.length / count)]);
}

function rowFor(packet, ordinal) {
  const bodyJson = JSON.stringify(packet);
  return {
    ordinal,
    sourceItemId: packet.sourceItemId,
    bodyJson,
    bodyBytes: encoder.encode(bodyJson).byteLength,
    packetSha256: packet.packetSha256
  };
}

function chunkFingerprint(rows) {
  return sha256(rows.map(row => `${row.ordinal}\u0000${row.sourceItemId}\u0000${row.bodyJson}`).join("\n"));
}

function moduleForChunk(index, rows) {
  const compact = JSON.stringify(rows.map(row => [
    row.ordinal,
    row.sourceItemId,
    row.bodyJson,
    row.bodyBytes,
    row.packetSha256
  ]));
  const compressed = gzipSync(Buffer.from(compact, "utf8"), { level: 9 });
  const base64 = compressed.toString("base64");
  return {
    text: `// Generated by scripts/materialize-forkrecipe-step7e-live-pilot.mjs. Do not hand-edit.\nexport const STEP7E_CHUNK_GZIP_BASE64 = ${JSON.stringify(base64)};\n`,
    compressedBytes: compressed.byteLength,
    encodedBytes: Buffer.byteLength(base64, "utf8")
  };
}

function manifestModule(manifest) {
  return `// Generated by scripts/materialize-forkrecipe-step7e-live-pilot.mjs. Do not hand-edit.\nexport const STEP7E_LIVE_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
}

function indexModule(chunkCount) {
  const imports = Array.from({ length: chunkCount }, (_, index) => {
    const suffix = String(index).padStart(3, "0");
    return `import { STEP7E_CHUNK_GZIP_BASE64 as chunk${suffix} } from "./chunk-${suffix}.mjs";`;
  }).join("\n");
  const names = Array.from({ length: chunkCount }, (_, index) => `chunk${String(index).padStart(3, "0")}`).join(",\n  ");
  return `${imports}\n\nconst CHUNKS = Object.freeze([\n  ${names}\n]);\n\nexport { STEP7E_LIVE_MANIFEST } from "./manifest.mjs";\nexport function step7eChunkBase64(index) {\n  return CHUNKS[index] ?? null;\n}\n`;
}

const args = parseArgs(process.argv.slice(2));
const sourceRoot = resolve(args.source);
const outputRoot = resolve(args.output);
const entries = await loadSourceEntries(sourceRoot);
if (entries.length !== FORKRECIPE_STEP7E_EXPECTED_RECIPE_COUNT) {
  throw new Error(`STEP7E_EXPECTED_${FORKRECIPE_STEP7E_EXPECTED_RECIPE_COUNT}_SOURCE_RECORDS_GOT_${entries.length}`);
}

const publicTitles = ALL_RECIPES.map(recipe => recipe.identity?.canonicalTitle || recipe.title || recipe.id);
const sourceAudit = buildForkRecipeStep7ePilot(entries, {
  commit: FORKRECIPE_STEP7E_EXPECTED_COMMIT,
  sourceRightsVerified: true,
  publicTitles
});
if (!sourceAudit.pass) throw new Error("STEP7E_SOURCE_AUDIT_MUST_PASS_BEFORE_LIVE_MATERIALIZATION");

const sortedPackets = [...sourceAudit.packets].sort((a, b) => a.sourceItemId.localeCompare(b.sourceItemId));
const selectedPackets = deterministicStep7eSelection(sortedPackets);
const selectedIds = selectedPackets.map(packet => packet.sourceItemId);
if (new Set(selectedIds).size !== STEP7E_LIVE_RECIPE_COUNT) throw new Error("STEP7E_LIVE_SELECTION_NOT_UNIQUE");

const rows = selectedPackets.map(rowFor);
const chunks = [];
let totalCompressedBytes = 0;
let totalEncodedBytes = 0;
let totalBodyBytes = 0;

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });

for (let index = 0; index < STEP7E_LIVE_CHUNK_COUNT; index += 1) {
  const start = index * STEP7E_LIVE_CHUNK_SIZE;
  const chunkRows = rows.slice(start, start + STEP7E_LIVE_CHUNK_SIZE);
  const module = moduleForChunk(index, chunkRows);
  const suffix = String(index).padStart(3, "0");
  await writeFile(resolve(outputRoot, `chunk-${suffix}.mjs`), module.text, "utf8");
  const descriptor = {
    chunkIndex: index,
    firstOrdinal: chunkRows[0].ordinal,
    lastOrdinal: chunkRows.at(-1).ordinal,
    recipeCount: chunkRows.length,
    firstSourceItemId: chunkRows[0].sourceItemId,
    lastSourceItemId: chunkRows.at(-1).sourceItemId,
    bodyBytes: chunkRows.reduce((sum, row) => sum + row.bodyBytes, 0),
    chunkSha256: chunkFingerprint(chunkRows),
    compressedBytes: module.compressedBytes,
    encodedBytes: module.encodedBytes
  };
  chunks.push(descriptor);
  totalCompressedBytes += module.compressedBytes;
  totalEncodedBytes += module.encodedBytes;
  totalBodyBytes += descriptor.bodyBytes;
}

const manifest = {
  schemaVersion: "forkrecipe-step7e-live-pilot-v1",
  sourceRepository: "futurechef/forkrecipe-recipes",
  sourceCommit: FORKRECIPE_STEP7E_EXPECTED_COMMIT,
  sourceUniverseCount: FORKRECIPE_STEP7E_EXPECTED_RECIPE_COUNT,
  sourceAuditPilotSha256: sourceAudit.pilotSha256,
  liveRecipeCount: STEP7E_LIVE_RECIPE_COUNT,
  chunkSize: STEP7E_LIVE_CHUNK_SIZE,
  chunkCount: STEP7E_LIVE_CHUNK_COUNT,
  selectionMethod: "SORT_SOURCE_ITEM_ID_THEN_FLOOR_I_TIMES_UNIVERSE_DIVIDED_BY_500",
  firstSourceItemId: rows[0].sourceItemId,
  lastSourceItemId: rows.at(-1).sourceItemId,
  totalBodyBytes,
  totalCompressedBytes,
  totalEncodedBytes,
  livePilotFingerprintSha256: sha256(chunks.map(chunk => chunk.chunkSha256).join("\n")),
  boundaries: {
    runtimeFetch: false,
    publicRuntimeActivationAuthorized: false,
    recommendationEligible: false,
    nutritionAuthorityImported: false,
    dietaryOrAllergenClaimsDerived: false,
    ratioValuesPromotedToAbsoluteQuantities: false,
    futureRecipeBodyD1ShardsCreated: false,
    existingCulinaryControlD1Only: true
  },
  chunks
};

await Promise.all([
  writeFile(resolve(outputRoot, "manifest.mjs"), manifestModule(manifest), "utf8"),
  writeFile(resolve(outputRoot, "index.mjs"), indexModule(STEP7E_LIVE_CHUNK_COUNT), "utf8"),
  writeFile(resolve(outputRoot, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8")
]);

process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);
